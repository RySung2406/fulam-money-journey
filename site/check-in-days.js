function ref(zh, en, zhUrl, enUrl) {
  return { ifecZh: zh, ifecEn: en, ifecZhUrl: zhUrl, ifecEnUrl: enUrl || zhUrl };
}
function more(zh, en, zhUrl, enUrl) {
  return { moreZh: zh, moreEn: en, moreZhUrl: zhUrl, moreEnUrl: enUrl || zhUrl };
}
function abc(a, b, c) {
  return [
    { k: 'A', zh: a[0], en: a[1] },
    { k: 'B', zh: b[0], en: b[1] },
    { k: 'C', zh: c[0], en: c[1] }
  ];
}
function day(n, week, title, terms, guide, scene, question, opts, method, source, extra) {
  return {
    n,
    placeZh: week[0],
    placeEn: week[1],
    year: '2026',
    titleZh: title[0],
    titleEn: title[1],
    conceptZh: terms[0],
    conceptEn: terms[1],
    bgZh: guide[0],
    bgEn: guide[1],
    sceneZh: scene[0],
    sceneEn: scene[1],
    qZh: question[0],
    qEn: question[1],
    opts,
    tipZh: method[0],
    tipEn: method[1],
    ...source,
    ...(extra || {})
  };
}

